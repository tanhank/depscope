// TestYarnLockParsing 验证 yarn.lock v1 文本解析的准确性。
func TestYarnLockParsing(t *testing.T) {
	sample := `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.5.5":
  version "7.5.5"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.5.5.tgz#bc0782f6d69f7b7d49531219699b988f669a8f9d"
  dependencies:
    "@babel/highlight" "^7.0.0"

lodash@^4.17.20, lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#679591c564c3bffaae8454cf0b3df370c3d6911c"
`

	entries, err := parseYarnLockDocument([]byte(sample))
	if err != nil {
		t.Fatalf("failed to parse sample yarn.lock: %v", err)
	}

	lodashEntry, ok := entries["lodash@^4.17.21"]
	if !ok {
		t.Fatalf("missing lodash@^4.17.21 in parsed entries")
	}
	if lodashEntry.version != "4.17.21" {
		t.Fatalf("lodash version = %q, want 4.17.21", lodashEntry.version)
	}

	babelEntry, ok := entries["@babel/code-frame@^7.0.0"]
	if !ok {
		t.Fatalf("missing @babel/code-frame@^7.0.0 in parsed entries")
	}
	if babelEntry.version != "7.5.5" {
		t.Fatalf("babel code-frame version = %q, want 7.5.5", babelEntry.version)
	}
	if babelEntry.dependencies["@babel/highlight"] != "^7.0.0" {
		t.Fatalf("missing subdependency @babel/highlight")
	}
}

// TestYarnProjectScan 验证 yarn.lock 项目的检测与扫描。
func TestYarnProjectScan(t *testing.T) {
	tempDir := t.TempDir()

	pkgJSON := `{
  "name": "yarn-demo",
  "version": "1.0.0",
  "dependencies": {
    "lodash": "^4.17.20"
  }
}`
	yarnLock := `# yarn lockfile v1

lodash@^4.17.20:
  version "4.17.21"
`

	if err := os.WriteFile(filepath.Join(tempDir, "package.json"), []byte(pkgJSON), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tempDir, "yarn.lock"), []byte(yarnLock), 0o600); err != nil {
		t.Fatal(err)
	}

	scanner := newTestScanner(t, &testVulnerabilities{})

	clock := func() time.Time { return time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC) }
	res, err := Scan(context.Background(), tempDir, Options{
		Scanner: scanner,
		Clock:   clock,
	})
	if err != nil {
		t.Fatalf("Scan returned error: %v", err)
	}

	if len(res.Formats) != 1 || res.Formats[0].Format != FormatNPMYarnLock {
		t.Fatalf("formats = %+v, want FormatNPMYarnLock", res.Formats)
	}
	if len(res.Dependencies.Nodes) != 1 {
		t.Fatalf("nodes count = %d, want 1", len(res.Dependencies.Nodes))
	}
	node := res.Dependencies.Nodes[0]
	if node.Package.Name != "lodash" || node.Version == nil || *node.Version != "4.17.21" {
		t.Fatalf("unexpected node: %+v", node)
	}
	if node.Relationship != model.DependencyDirect {
		t.Fatalf("node relationship = %v, want Direct", node.Relationship)
	}
}
